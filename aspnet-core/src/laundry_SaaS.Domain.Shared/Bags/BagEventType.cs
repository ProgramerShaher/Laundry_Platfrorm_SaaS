namespace laundry_SaaS.Bags;

/// <summary>
/// يمثل نوع الحدث التشغيلي الخاص بتتبع حقيبة الملابس وسلسلة حيازتها المادية (Chain of Custody).
/// يقتصر هذا السجل على حركة الحقيبة ولا يستخدم لتتبع مراحل المعالجة التفصيلية (كالغسيل والكي) الخاصة بالطلب.
/// </summary>
public enum BagEventType
{
    /// <summary>
    /// تم إنشاء الحقيبة وربطها برقم الطلب وتوليد رمز الاستجابة السريعة (QR Code).
    /// </summary>
    Created = 1,

    /// <summary>
    /// تم استلام الحقيبة من العميل وإغلاقها بواسطة السائق.
    /// </summary>
    PickedUpFromCustomer = 2,

    /// <summary>
    /// وصلت الحقيبة إلى مقر المغسلة وتم تسليمها إلى مسؤول الاستقبال والفرز.
    /// </summary>
    ReceivedAtLaundry = 3,

    /// <summary>
    /// فُتحت الحقيبة وبدأت عمليات المعالجة والغسيل للملابس التي بداخلها.
    /// </summary>
    Processing = 4,

    /// <summary>
    /// تم الانتهاء من تجهيز وتغليف الملابس وإعادتها إلى حقيبة التسليم لتصبح جاهزة للانطلاق.
    /// </summary>
    Ready = 5,

    /// <summary>
    /// استلم سائق التوصيل الحقيبة من المغسلة وبدأ رحلة تسليمها للعميل.
    /// </summary>
    PickedUpForDelivery = 6,

    /// <summary>
    /// تم تسليم الحقيبة إلى العميل بنجاح واكتملت دورة حيازتها.
    /// </summary>
    Delivered = 7
}
