namespace laundry_SaaS.Inspections;

/// <summary>
/// يمثل حالة محضر المعاينة والفحص الفني للملابس عند وصولها للمغسلة.
/// يضمن النظام محضر فحص رسمي واحد لكل طلب، مع إمكانية إعادة فتحه بضوابط وأسباب محددة بدلاً من إنشاء محاضر مكررة.
/// </summary>
public enum InspectionStatus
{
    /// <summary>
    /// بدأ الفني فحص محتويات الحقيبة ومطابقة القطع.
    /// </summary>
    Started = 1,

    /// <summary>
    /// تم الانتهاء من الفحص، وتأكيد الكميات، وتوثيق الأضرار السابقة إن وجدت.
    /// </summary>
    Completed = 2,

    /// <summary>
    /// تمت إعادة فتح محضر الفحص بقرار إداري لتعديل أو تدقيق بند معين مع ذكر سبب الإعادة.
    /// </summary>
    Reopened = 3
}
