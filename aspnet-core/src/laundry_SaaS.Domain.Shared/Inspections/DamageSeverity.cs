namespace laundry_SaaS.Inspections;

/// <summary>
/// يحدد مستوى جسامة وتأثير الضرر المرصود على القطعة.
/// </summary>
public enum DamageSeverity
{
    /// <summary>
    /// ضرر طفيف لا يؤثر بشكل ملحوظ على مظهر القطعة أو وظيفتها (مثل بقعة صغيرة جداً أو خيط منسول).
    /// </summary>
    Minor = 1,

    /// <summary>
    /// ضرر متوسط وواضح للعين ولكنه لا يمنع استخدام القطعة (مثل تمزق بسيط أو بهتان متوسط).
    /// </summary>
    Moderate = 2,

    /// <summary>
    /// ضرر جسيم وكبير يؤثر جوهرياً على القطعة (مثل حرق كبير أو تمزق واسع أو بقعة بارزة في واجهة القطعة).
    /// </summary>
    Severe = 3
}
