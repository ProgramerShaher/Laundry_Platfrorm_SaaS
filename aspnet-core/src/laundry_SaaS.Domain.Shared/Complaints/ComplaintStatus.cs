namespace laundry_SaaS.Complaints;

/// <summary>
/// يمثل الحالات التشغيلية لمعالجة شكاوى العملاء.
/// تعد الشكوى سجلاً مهماً لخدمة العملاء والتدقيق ولا يتم حذفها ناعماً (No Soft Delete).
/// </summary>
public enum ComplaintStatus
{
    /// <summary>
    /// تم تقديم الشكوى حديثاً وبانتظار بدء المراجعة من المشرف أو خدمة العملاء.
    /// </summary>
    Open = 1,

    /// <summary>
    /// الشكوى قيد التحقيق والمراجعة مع المغسلة أو السائق للتحقق من ملابسات المشكلة.
    /// </summary>
    InReview = 2,

    /// <summary>
    /// تم التوصل إلى حل واعتماده (مثل تعويض مالي أو إعادة خدمة) وتوثيقه في معلومات الحل.
    /// </summary>
    Resolved = 3,

    /// <summary>
    /// تم إغلاق الشكوى نهائياً بعد التحقق ورضا العميل أو رفض المطالبة.
    /// </summary>
    Closed = 4
}
