namespace laundry_SaaS.PickupDelivery;

/// <summary>
/// يمثل دورة حياة وحالات مهمة توصيل وتسليم الملابس النظيفة إلى العميل وتحصيل قيمتها نقداً (Cash On Delivery).
/// تتيح المنظومة محاولات توصيل متعددة (Multiple Attempts) عند تعثر التسليم، مع حصر المهمة النشطة بواحدة فقط لنفس الطلب.
/// </summary>
public enum DeliveryTaskStatus
{
    /// <summary>
    /// تم إنشاء مهمة التوصيل وتعيينها للسائق المناسب.
    /// </summary>
    Assigned = 0,

    /// <summary>
    /// وافق السائق على استلام مهمة التوصيل.
    /// </summary>
    Accepted = 1,

    /// <summary>
    /// استلم السائق الملابس الجاهزة والمغلفة من مقر المغسلة وانطلق بها.
    /// </summary>
    PickedUpFromLaundry = 2,

    /// <summary>
    /// السائق في الطريق المباشر إلى موقع العميل لتسليم الطلب.
    /// </summary>
    OutForDelivery = 3,

    /// <summary>
    /// وصل السائق إلى موقع العميل وبانتظار تسليم الملابس وتحصيل المبلغ.
    /// </summary>
    Arrived = 4,

    /// <summary>
    /// تم تسليم الملابس للعميل بنجاح واستلام المبلغ المالي نقداً عند الاستلام.
    /// </summary>
    Delivered = 5,

    /// <summary>
    /// تعثرت محاولة التوصيل (مثل رفض العميل، عدم توفر المبلغ، أو عدم التواجد في الموقع).
    /// </summary>
    Failed = 6,

    /// <summary>
    /// تم إلغاء مهمة التوصيل لأسباب إدارية أو طارئة قبل إتمامها.
    /// </summary>
    Cancelled = 7
}
