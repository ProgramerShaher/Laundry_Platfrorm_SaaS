namespace laundry_SaaS.PickupDelivery;

/// <summary>
/// يمثل دورة حياة وحالات مهمة استلام الملابس من العميل بواسطة السائق.
/// تتيح المنظومة محاولات استلام متعددة (Multiple Attempts) لنفس الطلب في حال التعثر، 
/// مع ضمان وجود مهمة استلام نشطة واحدة فقط في الوقت نفسه.
/// </summary>
public enum PickupTaskStatus
{
    /// <summary>
    /// تم إنشاء المهمة وتعيينها لسائق محدد من قبل النظام أو المشرف.
    /// </summary>
    Assigned = 0,

    /// <summary>
    /// وافق السائق على استلام المهمة وبدأ الاستعداد لتنفيذها.
    /// </summary>
    Accepted = 1,

    /// <summary>
    /// انطلق السائق في رحلته وهو الآن في الطريق إلى موقع العميل.
    /// </summary>
    OutForPickup = 2,

    /// <summary>
    /// وصل السائق إلى الموقع الجغرافي للعميل وبانتظار تسلم الملابس.
    /// </summary>
    Arrived = 3,

    /// <summary>
    /// استلم السائق الملابس من العميل وتم إغلاق الحقيبة وتأكيد الاستلام.
    /// </summary>
    PickedUp = 4,

    /// <summary>
    /// اكتملت المهمة بنجاح ووصلت الملابس إلى مقر المغسلة.
    /// </summary>
    Completed = 5,

    /// <summary>
    /// تعثرت محاولة الاستلام لسبب تشغيلي (مثل عدم الرد، عنوان خاطئ، أو إلغاء من العميل عند الباب).
    /// </summary>
    Failed = 6,

    /// <summary>
    /// تم إلغاء المهمة من قبل الإدارة قبل وصول السائق للعميل.
    /// </summary>
    Cancelled = 7
}
