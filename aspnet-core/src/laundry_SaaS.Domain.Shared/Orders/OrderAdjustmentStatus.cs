namespace laundry_SaaS.Orders;

/// <summary>
/// يمثل حالة اعتماد أو رفض التعديل المالي/الكمي الذي تم اقتراحه على الطلب بعد عملية الفحص الفني.
/// يتطلب التعديل موافقة العميل إذا ترتبت عليه زيادة في المبلغ الإجمالي المطلوب دفعه.
/// </summary>
public enum OrderAdjustmentStatus
{
    /// <summary>
    /// التعديل معلق وبانتظار اتخاذ قرار بشأنه من العميل (موافقة أو رفض).
    /// </summary>
    Pending = 0,

    /// <summary>
    /// تمت موافقة العميل على التعديل، وتم تطبيق الفروقات المالية على إجمالي الطلب.
    /// </summary>
    Approved = 1,

    /// <summary>
    /// تم رفض التعديل من قبل العميل، وتتم المعالجة وفق البنود الأصلية المتفق عليها أو استبعاد البند المرفوض.
    /// </summary>
    Rejected = 2,

    /// <summary>
    /// تم إلغاء التعديل من قبل المغسلة قبل اتخاذ العميل للقرار.
    /// </summary>
    Cancelled = 3
}
