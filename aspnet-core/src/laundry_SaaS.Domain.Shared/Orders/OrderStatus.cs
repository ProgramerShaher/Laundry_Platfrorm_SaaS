namespace laundry_SaaS.Orders;

/// <summary>
/// يمثل الحالات التشغيلية والمالية الشاملة لدورة حياة الطلب من الإنشاء وحتى التسليم النهائي أو الإلغاء.
/// يعد هذا السجل المصدر الأساسي للحالة العامة (General Status) للطلب داخل النظام.
/// </summary>
public enum OrderStatus
{
    /// <summary>
    /// مسودة طلب تم إنشاؤها مبدئياً ولم يتم تأكيدها أو إرسالها بعد.
    /// </summary>
    Draft = 0,

    /// <summary>
    /// بانتظار جدولة وتعيين سائق لاستلام الطلب من موقع العميل.
    /// </summary>
    PendingPickup = 1,

    /// <summary>
    /// تم تعيين سائق لمهمة الاستلام وبانتظار قبوله أو انطلاقه.
    /// </summary>
    PickupAssigned = 2,

    /// <summary>
    /// السائق في الطريق إلى موقع العميل لاستلام الملابس.
    /// </summary>
    OutForPickup = 3,

    /// <summary>
    /// تم استلام الملابس بنجاح من العميل ووضعها في حقيبة الاستلام.
    /// </summary>
    PickedUp = 4,

    /// <summary>
    /// وصلت الملابس إلى مقر المغسلة وتم تسليمها لقسم الفرز والاستقبال.
    /// </summary>
    ReceivedAtLaundry = 5,

    /// <summary>
    /// الملابس قيد المعاينة والفحص الفني لمطابقة الكميات ورصد الأضرار المسبقة إن وجدت.
    /// </summary>
    Inspection = 6,

    /// <summary>
    /// الطلب معلق بانتظار موافقة العميل على تعديل السعر أو البنود الناتج عن الفحص.
    /// </summary>
    WaitingForAdjustmentApproval = 7,

    /// <summary>
    /// الطلب في مرحلة المعالجة الفعلية والغسيل؛ في هذه الحالة فقط تكون الخاصية CurrentProcessingStage غير فارغة.
    /// </summary>
    Processing = 8,

    /// <summary>
    /// اكتملت معالجة الطلب بالكامل وتغليفه، والطلب جاهز في المغسلة للتسليم إلى السائق.
    /// </summary>
    ReadyForDelivery = 9,

    /// <summary>
    /// استلم السائق الطلب وهو الآن في طريقه لتسليمه إلى موقع العميل.
    /// </summary>
    OutForDelivery = 10,

    /// <summary>
    /// تم تسليم الطلب بنجاح إلى العميل، وتحصيل المبلغ نقداً عند الاستلام (COD).
    /// </summary>
    Delivered = 11,

    /// <summary>
    /// تم إغلاق الطلب نهائياً بعد انتهاء فترة الشكاوى وتأكيد اكتمال كافة العمليات.
    /// </summary>
    Completed = 12,

    /// <summary>
    /// تم إلغاء الطلب؛ يتم توثيق سبب وتوقيت الإلغاء بدقة ولا يمكن استئناف الطلب بعدها.
    /// </summary>
    Cancelled = 13,

    /// <summary>
    /// الطلب متوقف مؤقتاً لسبب تشغيلي أو إداري يستدعي المراجعة.
    /// </summary>
    OnHold = 14,

    /// <summary>
    /// فشلت مهمة الاستلام من العميل (مثل عدم تواجد العميل أو خطأ العنوان).
    /// </summary>
    PickupFailed = 15,

    /// <summary>
    /// فشلت مهمة التوصيل إلى العميل (مثل رفض الاستلام أو تعذر التواصل).
    /// </summary>
    DeliveryFailed = 16
}
